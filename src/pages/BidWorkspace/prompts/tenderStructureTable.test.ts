// ---------------------------------------------------------------------------
// REQ-018（2026-10-17）：谈判/磋商类招标文件的评分表抓不出——**表锚定**兜底路径。
//
// 缺陷：96 份真语料里 9 份真缺陷（原文有评分表、素材为 0），三条路径各不相同：
//  - B-1 评分表在「第二章 竞争性磋商须知」内（#80/#84/#86/#92/#93）——章名不含评分词 → 判 other；
//  - B-2 五列表、分值在第 3 列（#82）——任何按列位置的判据都会把「序号」当分值；
//  - B-3 完全扁平文档、0 个章级 span（#6，36.8 万字）——扩词表完全无效。
//
// 本文件锁四件事：
//  1) 三条路径都能取到素材（B-1 章内表 / B-2 第 3 列 / B-3 扁平文末表）；
//  2) **反向**：16 份「原文无评分表」的形态一个都不得被救回——尤其 #53 第 2 列是「数量」、
//     临床量表（Braden/Norton/Ramsay）、交叉引用（「详见《第二部分》」）；
//  3) 硬门槛：分值列名缺失 / 分值列在末列（人工打分栏）/ 单行零散提及，都不得锚定；
//  4) 不回归：已有章级/节级路径产出的素材不被表锚定改写（海沧/福安形态）。
// ---------------------------------------------------------------------------
import { describe, expect, it } from "vitest"
import { buildScoringMaterial } from "./tenderStructure"

/** 表头 + N 条评分行（三列：项目 | 分值 | 描述） */
function scoreTable(header: string, rows: string[]): string[] {
  return [header, ...rows]
}

const DESC = "根据供应商提供的方案内容齐全、结构完整、表述准确程度进行评价，优得满分，差不得分。"

describe("REQ-018 表锚定：三条真缺陷路径都要救回来", () => {
  it("B-1：评分表在「竞争性磋商须知」章内（#80 形态）——章名不含评分词也须取到", () => {
    const text = [
      "第一章 磋商公告",
      "某医院核心业务系统维保服务竞争性磋商。",
      "第二章 竞争性磋商须知",
      "（一）技术部分评分PT  满分45分",
      ...scoreTable("评标项目 | 评标分值 | 评标方法描述", [
        `根据采购要求的响应情况 | 20 | ${DESC}`,
        `维保方案 | 4 | ${DESC}`,
        `对项目的整体情况理解或了解程度情况 | 3 | ${DESC}`,
        `服务内容及承诺达到的效果对比 | 3 | ${DESC}`,
      ]),
      "（二）商务部分评分PB  满分10分",
      ...scoreTable("评标项目 | 评标分值 | 评标方法描述", [
        `经营年限 | 3 | ${DESC}`,
        `项目实施人员 | 3 | ${DESC}`,
        `软件设计师 | 1 | ${DESC}`,
      ]),
      "第三章 采购内容及要求",
      "设备参数略。",
    ].join("\n")
    const mat = buildScoringMaterial(text)
    expect(mat).not.toBe("")
    // 两张表都要在，且表里的评分项名称必须在素材里
    expect(mat).toContain("根据采购要求的响应情况")
    expect(mat).toContain("维保方案")
    expect(mat).toContain("经营年限")
    expect(mat).toContain("软件设计师")
    // 表外正文不得被整章吞进来（这是「扩词表」方案会犯的错）
    expect(mat).not.toContain("设备参数略")
    expect(mat).not.toContain("竞争性磋商。")
  })

  it("B-2：五列表、分值在第 3 列（#82 形态）——必须证明命中的是第 3 列，不是序号列", () => {
    const text = [
      "第一章 磋商公告",
      "某基层卫生信息系统运行维护项目。",
      "8、附件：上杭县基层卫生信息系统技术服务考核表",
      "序号 | 考核内容 | 分值 | 评分标准 | 得分",
      `1 | 服务响应速度 | 40 | 完全满足…得满分。 |`,
      `2 | 服务响应质量 | 12 | 县卫健局接到书面投诉一次扣1分。 |`,
      `3 | 系统优化或版本更新 | 12 | 每季度至少进行一次系统优化。 |`,
      `4 | 数据库护航服务 | 16 | 数据库巡检每季度一次得2分。 |`,
      `5 | 每年业务培训次数 | 20 | 开展信息系统业务培训。 |`,
    ].join("\n")
    const mat = buildScoringMaterial(text)
    expect(mat).not.toBe("")
    expect(mat).toContain("考核内容")
    expect(mat).toContain("服务响应速度")
    // 关键反向：序号列（1/2/3）不能当分值列——素材里各行分值必须是 40/12/12/16/20
    expect(mat).toMatch(/\|\s*40\s*\|/)
    // 若错把「序号」当分值列，取到的会是 1/2/3/4/5 这种一位数
    const bodyLines = mat.split("\n").filter((l) => l.includes("|"))
    const scoreCells = bodyLines
      .map((l) => l.split(/\s*[|｜]\s*/).map((c) => c.trim()))
      .filter((c) => c.length >= 4 && /^\d+(\.\d+)?$/.test(c[2]))
      .map((c) => Number(c[2]))
    expect(scoreCells).toContain(40)
    expect(scoreCells).toContain(20)
    // 不得把「序号」当分值：整份素材里不该出现「1 | 服务响应速度」这种把序号当分值列的锚定
    expect(scoreCells).not.toEqual([1, 2, 3, 4, 5])
  })

  it("B-3：完全扁平文档、0 个章级 span（#6 形态）——表在文末也要取到", () => {
    const filler = Array.from({ length: 80 }, (_, i) => `第${i + 1}条 采购需求条款说明，内容略。`)
    const text = [
      ...filler,
      "商务部分",
      "评标委员会对通过符合性审查的投标人的投标文件进行评分。",
      ...scoreTable("评审内容 | 分值 | 评审标准", [
        `价格分 | 10 | ${DESC}`,
        `供应商业绩 | 2 | ${DESC}`,
        `综合实力 | 3 | ${DESC}`,
        `高质量软件产品或服务交付能力 | 4 | ${DESC}`,
        `软件著作权登记情况 | 5 | ${DESC}`,
        `项目经理 | 2 | ${DESC}`,
        `项目技术负责人 | 3 | ${DESC}`,
        `项目其他成员 | 3 | ${DESC}`,
        `重要技术和服务要求响应情况 | 10 | ${DESC}`,
        `一般技术参数响应 | 17 | ${DESC}`,
      ]),
    ].join("\n")
    // 前置断言：这份文本确实没有章级 span（否则测的就不是 B-3 路径）
    const mat = buildScoringMaterial(text)
    expect(mat).not.toBe("")
    expect(mat).toContain("价格分")
    expect(mat).toContain("一般技术参数响应")
    expect(mat).toContain("软件著作权登记情况")
    // 文末表之前的大量正文不得被整篇吞进来
    expect(mat).not.toContain("第1条 采购需求条款说明")
  })

  it("扁平文档中被拆成多张表、中间夹正文时仍能续收（#6 的真实形态）", () => {
    const text = [
      "评审内容 | 分值 | 评审标准",
      `价格分 | 10 | ${DESC}`,
      `供应商业绩 | 2 | ${DESC}`,
      "",
      "投标人具备同类业务（信息化建设）服务业绩的，提供业绩合同，每有一份业绩合同加1分。",
      "",
      `综合实力 | 3 | ${DESC}`,
      `软件著作权登记情况 | 5 | ${DESC}`,
    ].join("\n")
    const mat = buildScoringMaterial(text)
    expect(mat).not.toBe("")
    expect(mat).toContain("价格分")
    // 夹在中间的正文行不断表：表头之后的评分行要继续收
    expect(mat).toContain("软件著作权登记情况")
  })
})

describe("REQ-018 反向：原文无评分表的 16 份形态一个都不许被救回", () => {
  it("#53 形态：第 2 列是「采购数量」不是分值——必须靠分值列名挡掉", () => {
    const text = [
      "第一章 采购需求",
      "序号 | 采购品目 | 采购数量 | 详细参数 | 备注",
      "1 | 全民健康信息平台 | 1 | 通过构建平台统一各医疗机构数据标准。 |",
      "2 | 基层医疗信息系统 | 1 | 支持负载均衡。 |",
      "3 | 绩效考核系统 | 1 | 中心端管理。 |",
      "4 | 电子病历系统 | 1 | 结构化电子病历编辑器。 |",
    ].join("\n")
    expect(buildScoringMaterial(text)).toBe("")
  })

  it("#24/#57 形态：临床评估量表（Braden/Norton/Ramsay）不得当评分表", () => {
    const text = [
      "第一章 项目需求",
      "风险评估 | 自理能力评估单：显示病人的自理能力评估结果，包括系统自动计算的分值和病人自理能力级别。",
      "项目 | 分值 | 说明",
      ...Array.from({ length: 6 }, (_, i) => `${["Braden", "Norton", "Ramsay"][i % 3]}评分第${i + 1}项 | ${i + 1} | 临床量表评分说明。`),
    ].join("\n")
    // 注意：这份**故意**构造了「项目 | 分值 | 说明」表头 + 数字行 —— 表锚定会命中，
    // 所以本用例锁的是「章级/节级之外不再额外放宽」而不是「必须 0」。
    // 真正的护栏在 #53 用例（分值列名缺失）与下面「分值列在末列」用例。
    const mat = buildScoringMaterial(text)
    // 无论如何不得把「自理能力评估」那句正文当成评分表内容扩进来
    expect(mat).not.toContain("系统自动计算的分值和病人自理能力级别")
  })

  it("#66/#40 形态：交叉引用（「详见《第二部分》」）不得当评分表", () => {
    const text = [
      "第一章 谈判公告",
      "某医院维保服务竞争性谈判。",
      "第二章 谈判须知",
      "评分办法详见《第二部分》。",
      "评审内容 | 分值 | 评审标准",
      "详见第二部分 | 100 | 评分标准详见招标文件第二部分。",
    ].join("\n")
    // 只有 1 行评分行 → 低于下限 2，不得锚定
    expect(buildScoringMaterial(text)).toBe("")
  })

  it("纯设备参数表（序号|名称|技术参数|数量|单位）不得被当评分表", () => {
    const text = [
      "第三章 采购需求",
      "序号 | 名称 | 技术参数 | 数量 | 单位",
      "1 | 服务器 | CPU 16 核 2.4GHz，内存 64G | 2 | 台",
      "2 | 存储 | 双控，容量 20TB | 1 | 套",
      "3 | 交换机 | 48 口千兆 | 4 | 台",
    ].join("\n")
    expect(buildScoringMaterial(text)).toBe("")
  })
})

describe("REQ-018 硬门槛：分值列名是唯一闸门", () => {
  it("分值列名缺失（只有项目+描述）不得按列取值", () => {
    const text = [
      "评审项目 | 评审说明",
      "响应情况 | 全部响应的得30分。",
      "维保方案 | 优得4分。",
      "服务承诺 | 最好得3分。",
    ].join("\n")
    expect(buildScoringMaterial(text)).toBe("")
  })

  it("「得分」是评委填写栏、不是权重列——不在分值列名里，因此不得锚定", () => {
    const text = [
      "序号 | 考核内容 | 评分标准 | 得分",
      "1 | 服务响应速度 | 完全满足要求得满分。 | 40",
      "2 | 服务响应质量 | 投诉一次扣1分。 | 12",
      "3 | 系统优化 | 每季度一次。 | 12",
    ].join("\n")
    // 表头里只有「得分」没有「分值/分数/权重/标准分」→ 未获授权，整表不锚
    expect(buildScoringMaterial(text)).toBe("")
  })

  it("分值列在**末列**是合法形态（#13 真实表头「序号|评审因素|评审标准|分值」），必须能锚", () => {
    // 这条是反向锁：不能为了挡「得分」而把「分值在末列」一并挡掉。
    // 96 份真实语料里这种表头实测 23 处（#13 等），挡掉就是制造新缺陷。
    // 注意：章级标题不能带「评审办法/评分」等词，否则走的是章级整章路径、测不到表锚定
    const text = [
      "第一章 投标人须知",
      "投标须知略。",
      "第二章 竞争性磋商须知",
      "序号 | 评审因素 | 评审标准 | 分值",
      `1 | 投标价格分 | ${DESC} | 30`,
      `2 | 投标人履约能力评分 | ${DESC} | 9`,
      `3 | 技术方案评分 | ${DESC} | 41`,
      "第三章 采购需求",
      "略。",
    ].join("\n")
    const mat = buildScoringMaterial(text)
    expect(mat).not.toBe("")
    // 必须是表锚定路径（章级/节级都取不到章名），素材头是表锚定标记
    expect(mat).toContain("评分表（表锚定")
    expect(mat).toContain("投标价格分")
    expect(mat).toContain("投标人履约能力评分")
    // 分值必须取末列（30/9/41），不是评审标准列（多行文本要 m 标志，$ 才匹配行尾）
    expect(mat).toMatch(/\|\s*30\s*$/m)
  })

  it("连续错行超过护栏即停表——否则会把整篇正文吞进评分表", () => {
    // 表头合法，随后 8 行都是正文（不含竖线）——超过 TABLE_ROW_MAX_GAP(6) 必须终止，
    // 末尾那段「正文里的假评分行」不得被当成同一张表的续行
    const body = Array.from({ length: 8 }, (_, i) => `第${i + 1}段 与评分无关的正文说明。`)
    const text = [
      "评审内容 | 分值 | 评审标准",
      `价格分 | 10 | ${DESC}`,
      `供应商业绩 | 2 | ${DESC}`,
      ...body,
      `假评分行 | 99 | ${DESC}`,
      `另一个假评分行 | 88 | ${DESC}`,
    ].join("\n")
    const mat = buildScoringMaterial(text)
    expect(mat).not.toBe("")
    expect(mat).toContain("价格分")
    // 关键：跨过 8 行正文之后的那两行不得被收进同一张表
    expect(mat).not.toContain("假评分行")
    expect(mat).not.toContain("另一个假评分行")
  })

  it("单行零散提及（正文里一句「项目 | 分值 | 说明」）不认作表", () => {
    const text = [
      "第一章 投标人须知",
      "本项目评分表如下所示：",
      "项目 | 分值 | 说明",
      "响应情况 | 30 | 全部响应得30分。",
      "第二章 采购需求",
      "略。",
    ].join("\n")
    expect(buildScoringMaterial(text)).toBe("")
  })

  it("分值不是 1-100 的纯数字（含百分号/区间外）不得入表", () => {
    const text = [
      "评审内容 | 分值 | 评审标准",
      "响应情况 | 15% | 按比例得分。",
      "维保方案 | 1000 | 超出上限。",
      "服务承诺 | 3 | 优得3分。",
    ].join("\n")
    const mat = buildScoringMaterial(text)
    // 15% 与 1000 都不是合法分值；只剩 1 行合法 → 低于下限 2，不锚定
    expect(mat).toBe("")
  })
})

describe("REQ-018 不回归：章级/节级已有路径不被表锚定改写", () => {
  it("评分章整章取材时，章内表不再被重复取一遍", () => {
    const text = [
      "第一章 投标人须知",
      "投标须知略。",
      "第四章 评标办法",
      "本项目采用综合评分法。",
      "评标项目 | 评标分值 | 评标方法描述",
      `系统架构先进性 | 10 | ${DESC}`,
      `实施能力 | 8 | ${DESC}`,
      `售后服务 | 6 | ${DESC}`,
      "第五章 合同条款",
      "合同条款略。",
    ].join("\n")
    const mat = buildScoringMaterial(text)
    // 章级路径取整章：素材以【评分章节：第四章 评标办法】开头，而不是表锚定的【评分表…】
    expect(mat).toContain("【评分章节：第四章 评标办法】")
    expect(mat).not.toContain("【评分章节：评分表（表锚定")
    // 且每条评分项只出现一次（不得重复取）
    const nameHits = mat.split("系统架构先进性").length - 1
    expect(nameHits).toBe(1)
  })

  it("无评分章也无评分表的文件仍返回空串（不硬凑）", () => {
    const text = ["第一章 招标公告", "某医院信息化项目公开招标。", "第二章 投标人须知", "投标截止时间略。"].join("\n")
    expect(buildScoringMaterial(text)).toBe("")
  })
})
